"""Build the published pages from src/app.html and the catalog in data/.

prototype.html       the Claude Artifact (no document skeleton; the Artifact host adds one)
index.html           the GitHub Pages site: the shop with real-looking photos (the main site since 2026-11-14)
photo/index.html     the photo shop's first address; now only forwards to the root, keeping the #product part
classic/index.html   the original hand-drawn shop (frozen since 2026-11-13, never rebuilt)
The pictures stay in photo/img. Every page talks to the same shared board.
"""
import json
import pathlib

here = pathlib.Path(__file__).parent
src = (here / 'src' / 'app.html').read_text(encoding='utf-8')
base = json.loads((here / 'data' / 'base.json').read_text(encoding='utf-8'))
cpath = here / 'data' / 'content.json'
content = json.loads(cpath.read_text(encoding='utf-8')) if cpath.exists() else {}
qpath = here / 'data' / 'qa.json'
qa = json.loads(qpath.read_text(encoding='utf-8')) if qpath.exists() else {}
# Photos live in photo/img and are referenced relative to photo/index.html (and the Artifact's own files).
ppath = here / 'data' / 'photos.json'
photos = json.loads(ppath.read_text(encoding='utf-8')) if ppath.exists() else {}
photos = {pid: f for pid, f in photos.items()
          if all((here / 'photo' / f[k]).exists() for k in ('main', 'wide', 'scene'))}

# The shared board's Worker checks product ids against the catalog.
(here / 'api' / 'src' / 'pids.js').write_text(
    '// Generated by build.py from data/base.json\nexport const PIDS = ' + json.dumps([b['id'] for b in base]) + ';\n', encoding='utf-8')


def render(ph):
    data = ('const BASE=' + json.dumps(base, ensure_ascii=False, separators=(',', ':')) + ';\n'
            'const CONTENT=' + json.dumps(content, ensure_ascii=False, separators=(',', ':')) + ';\n'
            'const QA=' + json.dumps(qa, ensure_ascii=False, separators=(',', ':')) + ';\n'
            'const PHOTOS=' + json.dumps(ph, ensure_ascii=False, separators=(',', ':')) + ';')
    assert src.count('/*__DATA__*/') == 1
    return src.replace('/*__DATA__*/', data.replace('</', '<\\/'))


ICON = ("data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'%3E"
        "%3Crect x='6' y='22' width='52' height='36' rx='4' fill='%23C79661'/%3E"
        "%3Crect x='2' y='14' width='60' height='12' rx='3' fill='%239A6E3E'/%3E"
        "%3Crect x='27' y='14' width='10' height='44' fill='%23FFC93A'/%3E%3C/svg%3E")
head = f'''<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="挑货、刷卡、等快递、拆箱，一分钱不花。">
<meta name="theme-color" content="#EDF0F6">
<link rel="icon" href="{ICON}">
<style>:root{{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}}body{{margin:0}}img{{max-width:100%}}[hidden]{{display:none!important}}</style>
'''
# Only the Pages builds talk to the shared board; the Artifact keeps posts in the browser.
API = 'https://gjj-api.yingwang.dev'


def page(artifact):
    assert artifact.count('const API="";/*__API__*/') == 1
    p = artifact.replace('const API="";/*__API__*/', f'const API="{API}";')
    p = p.replace('<meta name="claude:viewport-fit-sides" content="cover">\n', '')
    split = p.index('</style>') + len('</style>')
    return head + p[:split] + '\n</head>\n<body>\n' + p[split:].lstrip() + '\n</body>\n</html>\n'


artifact = render(photos)
(here / 'prototype.html').write_text(artifact, encoding='utf-8')
# The root page sits one level above photo/, so its picture paths get the folder in front.
root_photos = {pid: {k: 'photo/' + v for k, v in f.items()} for pid, f in photos.items()}
(here / 'index.html').write_text(page(render(root_photos)), encoding='utf-8')
(here / 'photo' / 'index.html').write_text(
    '<!doctype html>\n<html lang="zh-CN">\n<head>\n<meta charset="utf-8">\n<title>赛博过家家</title>\n'
    '<link rel="canonical" href="https://yingwang.github.io/cyber-guojiajia/">\n'
    '<script>location.replace("../" + location.hash)</script>\n'
    '<meta http-equiv="refresh" content="0;url=../">\n</head>\n'
    '<body><a href="../">赛博过家家</a></body>\n</html>\n', encoding='utf-8')
print('products', len(base), 'with copy', sum(1 for b in base if b['id'] in content), 'with qa', len(qa),
      'with photos', len(photos), '| prototype', len(artifact))
